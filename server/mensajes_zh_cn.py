def traducir_mensaje(texto, traducir_nombre):
    for pattern, translation, names in PLANTILLAS_ZH_CN:
        match = pattern.fullmatch(texto)
        if match:
            values = list(match.groups())
            for index in names:
                values[index] = traducir_nombre(values[index])
            return translation.format(*values)
    return texto
